import { createHash } from 'node:crypto';
import {
  accessSync,
  constants,
  cpSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { homedir } from 'node:os';
import { basename, delimiter, dirname, join, resolve } from 'node:path';

const CONFIG_CONTENT = `# Generated by tacet init; edit to customize.
escalation:
  autonomy: medium
handoff:
  warn: 0.55
  handoff: 0.7
  hard: 0.85
`;
const LOCAL_IGNORE = '.tacet/local.yaml';

const AGENT_CLIS = [
  { command: 'claude', credentialEnv: ['ANTHROPIC_API_KEY', 'ANTHROPIC_AUTH_TOKEN'] },
  { command: 'codex', credentialEnv: ['CODEX_API_KEY', 'OPENAI_API_KEY'] },
  { command: 'gemini', credentialEnv: ['GEMINI_API_KEY', 'GOOGLE_API_KEY'] },
  { command: 'opencode', credentialEnv: [] },
  { command: 'goose', credentialEnv: ['GOOSE_API_KEY'] },
] as const;

export interface AgentCli {
  command: string;
  installed: boolean;
  credentialEnvConfigured: boolean;
}

function requireRepoDirectory(path: string): void {
  if (!statSync(path).isDirectory())
    throw new Error(`Repository path must be a directory: ${path}`);
}

export interface InitResult {
  configCreated: boolean;
  gitignoreUpdated: boolean;
  agents: AgentCli[];
}

export interface UninstallOptions {
  repoRoot: string;
  apply?: boolean;
  purge?: boolean;
  homeDir?: string;
  now?: Date;
}

export interface UninstallResult {
  removals: string[];
  backupPath?: string;
  applied: boolean;
}

function isMissing(error: unknown): boolean {
  return (error as NodeJS.ErrnoException).code === 'ENOENT';
}

function pathExists(path: string): boolean {
  try {
    lstatSync(path);
    return true;
  } catch (error) {
    if (isMissing(error)) return false;
    throw error;
  }
}

function requireDirectory(path: string, label: string): void {
  const stat = lstatSync(path);
  if (!stat.isDirectory() || stat.isSymbolicLink()) {
    throw new Error(`${label} must be a directory, not a symbolic link: ${path}`);
  }
}

function requireRegularFile(path: string, label: string): void {
  const stat = lstatSync(path);
  if (!stat.isFile() || stat.isSymbolicLink()) {
    throw new Error(`${label} must be a regular file, not a symbolic link: ${path}`);
  }
}

function isExecutable(path: string): boolean {
  try {
    if (!statSync(path).isFile()) return false;
    accessSync(path, constants.X_OK);
    return true;
  } catch {
    return false;
  }
}

export function detectAgentClis(
  pathValue = process.env.PATH ?? '',
  env: NodeJS.ProcessEnv = process.env,
): AgentCli[] {
  const directories = pathValue.split(delimiter).filter(Boolean);
  return AGENT_CLIS.map(({ command, credentialEnv }) => ({
    command,
    installed: directories.some((directory) => isExecutable(join(directory, command))),
    credentialEnvConfigured: credentialEnv.some((name) => Boolean(env[name])),
  }));
}

export function initRepo(
  repoRoot: string,
  options: { path?: string; env?: NodeJS.ProcessEnv } = {},
): InitResult {
  const root = resolve(repoRoot);
  requireRepoDirectory(root);

  const tacetDir = join(root, '.tacet');
  if (pathExists(tacetDir)) requireDirectory(tacetDir, '.tacet');
  else mkdirSync(tacetDir);

  const configPath = join(tacetDir, 'tacet.yaml');
  let configCreated = false;
  try {
    writeFileSync(configPath, CONFIG_CONTENT, { flag: 'wx', mode: 0o644 });
    configCreated = true;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
    requireRegularFile(configPath, 'Config file');
  }

  const gitignorePath = join(root, '.gitignore');
  let gitignoreUpdated = false;
  if (pathExists(gitignorePath)) {
    requireRegularFile(gitignorePath, '.gitignore');
    const contents = readFileSync(gitignorePath, 'utf8');
    if (!contents.split(/\r?\n/).includes(LOCAL_IGNORE)) {
      const eol = contents.includes('\r\n') ? '\r\n' : '\n';
      const separator = contents.length > 0 && !contents.endsWith('\n') ? eol : '';
      writeFileSync(gitignorePath, `${separator}${LOCAL_IGNORE}${eol}`, { flag: 'a' });
      gitignoreUpdated = true;
    }
  } else {
    writeFileSync(gitignorePath, `${LOCAL_IGNORE}\n`, { flag: 'wx', mode: 0o644 });
    gitignoreUpdated = true;
  }

  return {
    configCreated,
    gitignoreUpdated,
    agents: detectAgentClis(options.path ?? options.env?.PATH, options.env),
  };
}

function backupLocation(repoRoot: string, homeDir: string, now: Date): string {
  const repoHash = createHash('sha256').update(repoRoot).digest('hex').slice(0, 12);
  const timestamp = now.toISOString().replaceAll(/[:.]/g, '-');
  return join(
    homeDir,
    '.tacet',
    'backups',
    `${basename(repoRoot)}-${repoHash}`,
    `uninstall-${timestamp}`,
  );
}

function inspectUninstall(opts: UninstallOptions): {
  root: string;
  tacetDir: string;
  removals: string[];
  backupPath?: string;
} {
  const root = resolve(opts.repoRoot);
  requireRepoDirectory(root);
  const tacetDir = join(root, '.tacet');
  if (!pathExists(tacetDir)) return { root, tacetDir, removals: [] };
  requireDirectory(tacetDir, '.tacet');

  if (opts.purge) {
    return {
      root,
      tacetDir,
      removals: [tacetDir],
      backupPath: backupLocation(root, opts.homeDir ?? homedir(), opts.now ?? new Date()),
    };
  }

  const configPath = join(tacetDir, 'tacet.yaml');
  if (!pathExists(configPath)) return { root, tacetDir, removals: [] };
  requireRegularFile(configPath, 'Config file');
  if (readFileSync(configPath, 'utf8') !== CONFIG_CONTENT) {
    return { root, tacetDir, removals: [] };
  }
  const removals = [configPath];
  if (readdirSync(tacetDir).length === 1) removals.push(tacetDir);
  return { root, tacetDir, removals };
}

function ensureBackupDirectories(homeDir: string, backupPath: string): void {
  const tacetHome = join(homeDir, '.tacet');
  const backups = join(tacetHome, 'backups');
  const repoBackups = join(backups, basename(dirname(backupPath)));
  for (const directory of [tacetHome, backups, repoBackups]) {
    if (pathExists(directory)) requireDirectory(directory, 'Backup directory');
    else mkdirSync(directory, { mode: 0o700 });
  }
}

export function uninstallRepo(opts: UninstallOptions): UninstallResult {
  const plan = inspectUninstall(opts);
  if (!opts.apply || plan.removals.length === 0) {
    return {
      removals: plan.removals,
      ...(plan.backupPath ? { backupPath: plan.backupPath } : {}),
      applied: false,
    };
  }

  if (opts.purge) {
    if (!plan.backupPath) return { removals: [], applied: false };
    const backupRoot = plan.backupPath;
    ensureBackupDirectories(opts.homeDir ?? homedir(), backupRoot);
    mkdirSync(backupRoot, { mode: 0o700 });
    try {
      cpSync(plan.tacetDir, join(backupRoot, '.tacet'), {
        recursive: true,
        errorOnExist: true,
        force: false,
      });
    } catch (error) {
      rmSync(backupRoot, { recursive: true, force: true });
      throw error;
    }
    rmSync(plan.tacetDir, { recursive: true });
  } else {
    const configPath = join(plan.tacetDir, 'tacet.yaml');
    rmSync(configPath);
    if (plan.removals.includes(plan.tacetDir)) rmdirSync(plan.tacetDir);
  }
  return {
    removals: plan.removals,
    ...(plan.backupPath ? { backupPath: plan.backupPath } : {}),
    applied: true,
  };
}
