import { z } from 'zod';
import { Autonomy, Id, Timestamp, TokenCount, Usd } from './common.js';

/** Task priority, highest first. */
export const Priority = z.enum(['p0', 'p1', 'p2', 'p3']);
export type Priority = z.infer<typeof Priority>;

/** Spending limits for one task. Either limit may be omitted. */
export const Budget = z.object({
  usd: Usd.optional().describe('Hard cap on spend for the task, in US dollars'),
  tokens: TokenCount.optional().describe('Hard cap on total tokens for the task'),
});
export type Budget = z.infer<typeof Budget>;

/** Per-role model tier override, e.g. `{ adapter: "claude-sdk", model: "sonnet", effort: "low" }`. */
export const TierOverride = z.object({
  adapter: z.string().min(1).optional(),
  model: z.string().min(1).optional(),
  effort: z.string().min(1).optional(),
});
export type TierOverride = z.infer<typeof TierOverride>;

/**
 * A unit of work routed from the Conductor to a Mini-conductor (ARCHITECTURE.md §2.1).
 * On the wire it travels as an A2A Task plus the `urn:tacet:a2a-ext:task:v1` metadata (TaskExt).
 */
export const Task = z.object({
  id: Id.describe('A2A Task.id, generated by the Mini-conductor'),
  goal: z.string().min(1),
  acceptanceCriteria: z.array(z.string().min(1)),
  budget: Budget.optional(),
  priority: Priority.default('p2'),
  parentId: Id.optional().describe('Parent task, carried as A2A referenceTaskIds'),
  contextId: Id.optional().describe('A2A contextId: the cross-repo goal or workflow'),
  createdAt: Timestamp,
});
export type Task = z.infer<typeof Task>;

/** Task metadata carried under `metadata["urn:tacet:a2a-ext:task:v1"]` (ADR-003 §4). */
export const TaskExt = z.object({
  acceptanceCriteria: z.array(z.string().min(1)),
  budget: Budget.optional(),
  priority: Priority.optional(),
  autonomy: Autonomy.optional(),
  tiers: z.record(z.string(), TierOverride).optional().describe('Tier overrides keyed by role'),
  deadline: Timestamp.optional(),
});
export type TaskExt = z.infer<typeof TaskExt>;

export const TASK_EXT_URI = 'urn:tacet:a2a-ext:task:v1';
